for (const [directory, provider, authMethod, requiredEnv] of REMAINING) {
  if (CONNECTOR_LIVE_META[directory]) {
    continue;
  }
  const slug = directory === "github" ? "github" : directory;
  const smoke =
    directory === "github"
      ? "scripts/package-acceptance-smoke.mjs"
      : `scripts/package-acceptance-${slug}-smoke.mjs`;
  CONNECTOR_LIVE_META[directory] = {
    ...DEFAULT_META,
    provider,
    authMethod,
    requiredEnv,
    credentialSignals: requiredEnv,
    mockSmoke: smoke,
    riskLevel:
      directory === "stripe" || directory === "shopify"
        ? RISK.HIGH
        : RISK.MEDIUM,
    priorityGroup:
      directory === "stripe" || directory === "shopify"
        ? "saas_mutation"
        : "saas_read",
  };
}

export function metaForDirectory(directory) {
  const base = CONNECTOR_LIVE_META[directory];
  if (!base) {
    return {
      ...DEFAULT_META,
      provider: directory,
      authMethod: "unknown",
      mockSmoke: `scripts/package-acceptance-${directory}-smoke.mjs`,
    };
  }
  return base;
}
